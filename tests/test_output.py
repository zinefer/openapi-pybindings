def test_main_exit_codes(project: Project, capsys: pytest.CaptureFixture[str]) -> None:
    base = [str(project.spec_dir), "-m", "api", "-o", str(project.client_dir)]
    root = ["--import-path", str(project.root)]

    assert main([*base, *root, "--check"]) == 1
    assert "error: " in capsys.readouterr().err

    assert main([*base, *root]) == 0
    assert main([*base, *root, "--check"]) == 0

    assert main([*base, *root, "--versions", "v1"]) == 1
    err = capsys.readouterr().err
    assert "error: files.yaml#/paths/~1v2~1health/get: path must start with" in err

    assert main([*base, *root, "--versions", "v1", "v2"]) == 0
    assert main([*base, *root, "movies.yaml"]) == 0
    assert (project.client_dir / "files.py").exists()

    assert main([str(project.root / "nope"), "-m", "api", "-o", "x"]) == 2
    assert "is not a directory" in capsys.readouterr().err


