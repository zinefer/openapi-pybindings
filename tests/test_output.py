async def test_custom_client_package_outside_the_models(project: Project) -> None:
    out = project.root / "movie_client"
    from openapi_pybindings import generate

    assert (
        generate(
            project.spec_dir,
            out,
            models_package="api",
            client_package="movie_client",
        )
        == []
    )
    assert (
        "from movie_client import QueryValue, Transport"
        in (out / "movies.py").read_text()
    )
    import importlib

    module = importlib.import_module("movie_client.movies")
    try:
        transport = RecordingTransport(response=[])
        assert await module.list_movies(transport, title="Alien") == []
    finally:
        for name in [n for n in sys.modules if n.startswith("movie_client")]:
            del sys.modules[name]


def run_cli(
    project: Project, *args: str, cwd: Path | None = None
) -> subprocess.CompletedProcess[str]:
    """The installed console script, as a project would run it via `uv run`."""
    script = Path(sys.executable).parent / "openapi-pybindings"
    return subprocess.run(
        [str(script), *args],
        cwd=cwd or project.root,
        capture_output=True,
        text=True,
        env={**os.environ, "PYTHONPATH": ""},
    )


def test_console_script_imports_models_from_the_working_directory(
    project: Project,
) -> None:
    result = run_cli(project, str(project.spec_dir), "-m", "api", "-o", "api/client")
    assert result.returncode == 0, result.stderr
    assert result.stderr == ""
    assert (project.client_dir / "movies.py").exists()

    result = run_cli(
        project, str(project.spec_dir), "-m", "api", "-o", "api/client", "--check"
    )
    assert (result.returncode, result.stderr) == (0, "")


def test_console_script_import_path(project: Project, tmp_path: Path) -> None:
    elsewhere = tmp_path / "elsewhere"
    elsewhere.mkdir()
    out = project.client_dir
    args = [str(project.spec_dir), "-m", "api", "-o", str(out)]

    result = run_cli(project, *args, cwd=elsewhere)
    assert result.returncode == 1
    assert "cannot import api.movies" in result.stderr

    result = run_cli(project, *args, "--import-path", str(project.root), cwd=elsewhere)
    assert result.returncode == 0, result.stderr


