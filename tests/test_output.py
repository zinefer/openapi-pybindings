def test_generate_is_idempotent(project: Project) -> None:
    assert project.generate() == []
    first = {p.name: p.read_text() for p in project.client_dir.iterdir()}
    assert project.generate() == []
    assert {p.name: p.read_text() for p in project.client_dir.iterdir()} == first


def test_stale_generated_modules_are_removed(project: Project) -> None:
    assert project.generate() == []
    (project.spec_dir / "files.yaml").unlink()
    assert project.generate() == []
    assert not (project.client_dir / "files.py").exists()
    assert (project.client_dir / "movies.py").exists()


def test_files_from_other_generators_are_left_alone(project: Project) -> None:
    project.client_dir.mkdir(parents=True)
    other = project.client_dir / "other.py"
    other.write_text("# GENERATED by some-other-tool from x.proto. Do not edit.\n")
    assert project.generate() == []
    assert other.exists()
    assert project.check() == []


def test_hand_written_files_are_never_removed(project: Project) -> None:
    project.client_dir.mkdir(parents=True)
    mine = project.client_dir / "helpers.py"
    mine.write_text("# my code\n")
    data = project.client_dir / "notes.txt"
    data.write_text("keep")
    assert project.generate() == []
    assert mine.read_text() == "# my code\n"
    assert data.read_text() == "keep"


def test_hand_written_files_are_never_overwritten(project: Project) -> None:
    project.client_dir.mkdir(parents=True)
    mine = project.client_dir / "movies.py"
    mine.write_text("# my code\n")
    problems = project.generate()
    assert problems == [f"{mine}: exists and was not generated, not overwriting"]
    assert mine.read_text() == "# my code\n"
    assert (project.client_dir / "files.py").exists()
    assert project.check() == [f"{mine}: exists and was not generated, not overwriting"]


def test_check(project: Project) -> None:
    assert project.check() == [
        f"{project.client_dir / name}: missing"
        for name in ("__init__.py", "files.py", "movies.py")
    ]
    assert not project.client_dir.exists(), "check must not write"

    assert project.generate() == []
    assert project.check() == []

    movies = project.client_dir / "movies.py"
    movies.write_text(movies.read_text() + "# edited\n")
    stale = project.client_dir / "old.py"
    stale.write_text("# GENERATED by openapi-pybindings from old.yaml. Do not edit.\n")
    (project.client_dir / "mine.py").write_text("# mine\n")
    assert project.check() == [
        f"{movies}: out of date",
        f"{stale}: stale, would be removed",
    ]


def test_check_reports_unsupported_shapes_too(project: Project) -> None:
    assert project.generate() == []
    problems = project.check(versions=["v1"])
    assert problems == [
        "files.yaml#/paths/~1v2~1files~1{name}/get: path must start with one of "
        "the versions ['v1']",
        "files.yaml#/paths/~1v2~1health/get: path must start with one of the "
        "versions ['v1']",
    ]
    # Nothing in files.yaml could be generated, so its module is kept as it was.
    project.generate(versions=["v1"])
    assert (project.client_dir / "files.py").exists()


def test_selecting_specs(project: Project) -> None:
    assert project.generate(specs=["files.yaml"]) == []
    assert sorted(p.name for p in project.client_dir.glob("*.py")) == [
        "__init__.py",
        "files.py",
    ]
    problems = project.generate(specs=["missing.yaml"])
    assert len(problems) == 1
    assert problems[0].startswith("missing.yaml: cannot load missing.yaml")
    assert (project.client_dir / "files.py").exists()


def test_selecting_specs_leaves_the_other_modules_alone(project: Project) -> None:
    assert project.generate() == []
    movies = (project.client_dir / "movies.py").read_text()
    (project.spec_dir / "files.yaml").write_text(
        (project.spec_dir / "files.yaml").read_text().replace("health", "ping")
    )
    assert project.generate(specs=["files.yaml"]) == []
    assert (project.client_dir / "movies.py").read_text() == movies
    assert "async def ping(" in (project.client_dir / "files.py").read_text()
    assert project.check(specs=["files.yaml"]) == []
    # A selected spec that no longer has operations still loses its module.
    (project.spec_dir / "files.yaml").write_text(
        'openapi: 3.0.3\ninfo: {title: files, version: "1"}\npaths: {}\n'
    )
    assert project.check(specs=["files.yaml"]) == [
        f"{project.client_dir / 'files.py'}: stale, would be removed"
    ]
    assert project.generate(specs=["files.yaml"]) == []
    assert not (project.client_dir / "files.py").exists()
    assert (project.client_dir / "movies.py").exists()


def test_excluding_specs(project: Project) -> None:
    assert project.generate() == []
    assert project.generate(exclude=["fil*.yaml"]) == []
    assert not (project.client_dir / "files.py").exists()
    assert (project.client_dir / "movies.py").exists()
    assert project.check(exclude=["fil*.yaml"]) == []
    # Excluding applies to a list of specs too.
    files, problems = project.render(specs=["movies.yaml"], exclude=["movies.*"])
    assert (sorted(files), problems) == (["__init__.py"], [])


