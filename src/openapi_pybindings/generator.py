class ModuleWriter:
    def __init__(
        self,
        spec_name: str,
        resolver: Resolver,
        *,
        models_package: str,
        client_package: str,
    ) -> None:
        self.spec_name = spec_name
        self.resolver = resolver
        self.models_package = models_package
        self.client_package = client_package
        self.api_modules: set[str] = set()
        self.primitive_imports: set[tuple[str, str]] = set()
        self.adapters: dict[str, str] = {}
        self.functions: list[str] = []
        self.function_names: set[str] = set()
        self.quotes_path = False
        self.uses_transport = False
        self.uses_query_value = False
        self._current = _Function()

    def model(self, ref: Ref) -> str:
        self.api_modules.add(ref.module)
        self._current.modules.add(ref.module)
        return f"{ref.module}.{ref.name}"

    def primitive(self, schema: dict[str, Any]) -> str | None:
        type_, format_ = schema.get("type"), schema.get("format")
        if not isinstance(type_, str) or not isinstance(format_, str | None):
            return None  # e.g. OpenAPI 3.1 `type: [string, integer]`
        annotation = _PRIMITIVES.get((type_, format_)) or _PRIMITIVES.get((type_, None))
        if annotation in _PRIMITIVE_IMPORTS:
            self.primitive_imports.add(_PRIMITIVE_IMPORTS[annotation])
        return annotation

    def literal(self, schema: dict[str, Any]) -> tuple[Scalar, bool] | None:
        """An inline `enum` as a `Literal`, and whether it allows null."""
        if "enum" not in schema:
            return None
        values = _list(schema["enum"], "enum")
        present = [v for v in values if v is not None]
        if present and all(isinstance(v, str) for v in present):
            members = [f'"{_escape(v)}"' for v in present]
            forms = ("{}", "{}", False)
        elif present and all(
            isinstance(v, int) and not isinstance(v, bool) for v in present
        ):
            members = [str(v) for v in present]
            forms = ("{}", "str({})", True)
        else:
            raise UnsupportedShape("enum values must be all strings or all integers")
        self.primitive_imports.add(("typing", "Literal"))
        scalar = Scalar(f"Literal[{', '.join(members)}]", *forms)
        return scalar, len(present) < len(values)

    def scalar(self, schema: Any, location: Loc) -> Scalar | None:
        """A schema as a single parameter value, or None if it is not one."""
        with _at(location):
            schema, _ = _without_null(_mapping(schema, "schema"))
            if "$ref" in schema:
                target, target_location = self.resolver.follow(schema, location)
                if "enum" in target:
                    annotation = self.model(
                        self.resolver.schema_ref(schema["$ref"], location.file)
                    )
                    return Scalar(annotation, "{}.value", "str({}.value)", False)
                return self.scalar(target, target_location)
            literal = self.literal(schema)
            if literal is not None:
                return literal[0]
            primitive = self.primitive(schema)
            if primitive is None:
                return None
            return Scalar(primitive, *_SCALAR_FORMS[primitive])

    def is_scalar(self, schema: Any, location: Loc) -> bool:
        """Like `scalar`, without recording anything the module would import."""
        target, _ = self.resolver.follow(schema, location)
        target, _ = _without_null(target)
        return "enum" in target or target.get("type") in (
            "string",
            "integer",
            "number",
            "boolean",
        )

    def body_type(self, schema: Any, location: Loc) -> PyType:
        """The Python type of a request or response body schema."""
        with _at(location):
            if schema is None:
                raise UnsupportedShape("body has no schema")
            schema, nullable = _without_null(_mapping(schema, "schema"))
            if "$ref" in schema:
                annotation = self.model(
                    self.resolver.schema_ref(schema["$ref"], location.file)
                )
                target, _ = self.resolver.follow(schema, location)
                target, target_nullable = _without_null(target)
                body = PyType(annotation, model="enum" not in target)
                nullable = nullable or target_nullable
            else:
                body = self._inline_type(schema, location)
        return PyType(_union([body.annotation, "None"])) if nullable else body

    def _inline_type(self, schema: dict[str, Any], location: Loc) -> PyType:
        for key in ("anyOf", "oneOf", "allOf"):
            if key in schema:
                return self._combined_type(schema, key, location)
        if schema.get("type") == "array":
            items = self.body_type(schema.get("items"), location / "items")
            return PyType(f"list[{items.annotation}]")
        if schema.get("type") == "object" and set(schema) <= {
            "type",
            "additionalProperties",
            *_ANNOTATION_KEYS,
        }:
            values = schema.get("additionalProperties")
            if isinstance(values, dict) and values:
                value_type = self.body_type(values, location / "additionalProperties")
                return PyType(f"dict[str, {value_type.annotation}]")
        literal = self.literal(schema)
        if literal is not None:
            scalar, nullable = literal
            return PyType(
                _union([scalar.annotation, "None"]) if nullable else scalar.annotation
            )
        primitive = self.primitive(schema)
        if primitive is not None:
            return PyType(primitive)
        kind = schema.get("type", "untyped")
        raise UnsupportedShape(
            f"inline {kind} schema; give it a components/schemas entry"
        )

    def _combined_type(self, schema: dict[str, Any], key: str, location: Loc) -> PyType:
        """`anyOf` / `oneOf` as a union, or an `allOf` of one schema as itself."""
        extra = sorted(
            k
            for k in schema
            if k != key and k not in _ANNOTATION_KEYS and not k.startswith("x-")
        )
        if extra:
            raise UnsupportedShape(f"{key} alongside {', '.join(extra)}")
        members = _list(schema[key], key)
        if key == "allOf":
            if len(members) != 1:
                raise UnsupportedShape(
                    f"allOf of {len(members)} schemas; "
                    "give the combination a components/schemas entry"
                )
            return self.body_type(members[0], location / key / 0)
        if not members:
            raise UnsupportedShape(f"empty {key}")
        types: list[PyType] = []
        for i, member in enumerate(members):
            with _at(location / key / i):
                member = _mapping(member, "schema")
            if member.get("type") == "null":
                types.append(_NONE)
            else:
                types.append(self.body_type(member, location / key / i))
        if len(types) == 1:
            return types[0]
        return PyType(_union([t.annotation for t in types]))

    def resolved_params(
        self, path_level: Any, operation_level: Any, operation: Loc
    ) -> list[tuple[dict[str, Any], Loc]]:
        """Path item parameters overridden by operation ones of the same name and
        location, each with where it was resolved from. Headers OpenAPI says to
        ignore are left out."""
        merged: dict[tuple[str, str], tuple[dict[str, Any], Loc]] = {}
        for raw_list, base in (
            (path_level, operation.parent() / "parameters"),
            (operation_level, operation / "parameters"),
        ):
            with _at(base):
                raw_params = _list(raw_list, "parameters")
            for i, raw in enumerate(raw_params):
                param, location = self.resolver.follow(raw, base / i, "parameter")
                with _at(location):
                    if not isinstance(param.get("name"), str) or not isinstance(
                        param.get("in"), str
                    ):
                        raise UnsupportedShape("parameter without a name or in")
                if (
                    param["in"] == "header"
                    and param["name"].lower() in _IGNORED_HEADERS
                ):
                    continue
                merged[(param["name"], param["in"])] = (param, location)
        return list(merged.values())

    def param(self, param: dict[str, Any], location: Loc) -> Param:
        with _at(location):
            return self._param(param, location)

    def _param(self, param: dict[str, Any], location: Loc) -> Param:
        where, name = param["in"], param["name"]
        if where not in _DEFAULT_STYLE:
            raise UnsupportedShape(f"{where} parameter {name}")
        if "content" in param:
            raise UnsupportedShape(f"parameter {name} uses content")
        required = where == "path" or param.get("required") is True
        style = param.get("style", _DEFAULT_STYLE[where])
        explode = param.get("explode", style == "form")
        if not isinstance(style, str) or not isinstance(explode, bool):
            raise UnsupportedShape(f"parameter {name} style or explode")

        schema_location = location / "schema"
        with _at(schema_location):
            schema = _mapping(param.get("schema") or {}, f"parameter {name} schema")
        schema, nullable = _without_null(schema)
        target, target_location = schema, schema_location
        if "$ref" in schema:
            target, target_location = self.resolver.follow(schema, schema_location)
            target, target_nullable = _without_null(target)
            nullable = nullable or target_nullable
        if nullable and required:
            # An optional parameter is None to leave it out; a required one has
            # no way to send null.
            raise UnsupportedShape(f"required parameter {name} is nullable")

        def unsupported_style() -> UnsupportedShape:
            return UnsupportedShape(
                f"{style} style{'' if explode else ' without explode'} "
                f"for {where} parameter {name}"
            )

        item: Scalar | None
        if target.get("type") == "array":
            shape = "array"
            items_location = target_location / "items"
            with _at(items_location):
                items = _mapping(target.get("items") or {}, "items")
                if _without_null(items)[1]:
                    raise UnsupportedShape(f"parameter {name} items may be null")
            item = self.scalar(items, items_location)
            if item is None:
                raise UnsupportedShape(f"parameter {name} items are not single values")
            annotation = f"list[{item.annotation}]"
            allowed = _ARRAY_SEPARATORS if where == "query" else {"simple"}
            if style not in allowed:
                raise unsupported_style()
        elif "$ref" in schema and (
            target.get("type") == "object" or "properties" in target
        ):
            shape, item = "object", None
            # deepObject has one form whatever `explode` says (its default is
            # false, but specs rarely spell out the true they mean).
            if where != "query" or not (
                (style == "form" and explode) or style == "deepObject"
            ):
                raise unsupported_style()
            properties = _mapping(target.get("properties") or {}, "properties")
            for prop, prop_schema in properties.items():
                prop_location = target_location / "properties" / prop
                if not self.is_scalar(prop_schema, prop_location):
                    raise UnsupportedShape(
                        f"parameter {name} property {prop} is not a single value",
                        prop_location,
                    )
            annotation = self.model(
                self.resolver.schema_ref(schema["$ref"], schema_location.file)
            )
        else:
            shape = "scalar"
            item = self.scalar(schema, schema_location)
            if item is None:
                raise UnsupportedShape(f"parameter {name} is not a single value")
            annotation = item.annotation
            if style != _DEFAULT_STYLE[where]:
                raise unsupported_style()
        return Param(
            name=_identifier(name),
            wire_name=name,
            location=where,
            annotation=annotation,
            required=required,
            shape=shape,
            item=item,
            style=style,
            explode=explode,
        )

    def path_value(self, p: Param) -> str:
        """The f-string expression for a path parameter. Anything that can hold
        reserved characters is percent-encoded, so a value can only ever fill its
        own path segment (or, for a list, its own comma separated item).
        """
        item = p.item
        assert item is not None
        if p.shape == "array":
            self._uses(item.text)
            if item.segment_safe:
                text = item.text.format("item")
            else:
                self._quote()
                text = f"quote({item.text.format('item')}, safe='')"
            if text == "item":
                return f"','.join({p.name})"
            return f"','.join({text} for item in {p.name})"
        if item.segment_safe:
            if item.text == "str({})":
                return p.name
            self._uses(item.text)
            return item.text.format(p.name)
        self._quote()
        self._uses(item.text)
        return f"quote({item.text.format(p.name)}, safe='')"

    def _quote(self) -> None:
        self.quotes_path = True
        self._current.locals.add("quote")

    def _uses(self, code: str) -> None:
        if "str(" in code:
            self._current.locals.add("str")

    def response(self, operation: dict[str, Any], location: Loc) -> PyType | None:
        """The return type, or None for an operation whose success responses are
        not JSON."""
        responses_location = location / "responses"
        with _at(responses_location):
            responses = _mapping(operation.get("responses") or {}, "responses")
        types: list[PyType] = []
        non_json: list[str] = []
        for code, raw in sorted(responses.items(), key=lambda kv: str(kv[0])):
            code = str(code)
            if not code.startswith("2"):
                continue
            response, response_location = self.resolver.follow(
                raw, responses_location / code, f"response {code}"
            )
            with _at(response_location):
                content = _mapping(response.get("content") or {}, "response content")
                if not content:
                    types.append(_NONE)
                    continue
                json_media = _json_content(content)
                if json_media is None:
                    non_json.append(code)
                    continue
            media_type, media = json_media
            types.append(
                self.body_type(
                    media.get("schema"),
                    response_location / "content" / media_type / "schema",
                )
            )
        if non_json:
            if any(t != _NONE for t in types):
                raise UnsupportedShape(
                    f"success responses {non_json} are not JSON but others are",
                    responses_location,
                )
            return None
        if not types:
            return _NONE
        if len({t.annotation for t in types}) == 1:
            return types[0]
        return PyType(_union([t.annotation for t in types]))

    def request_body(
        self, operation: dict[str, Any], location: Loc
    ) -> tuple[PyType, bool] | None:
        """The body's type, with `| None` if it is optional, and whether it is."""
        if operation.get("requestBody") is None:
            return None
        body, body_location = self.resolver.follow(
            operation["requestBody"], location / "requestBody", "request body"
        )
        with _at(body_location):
            content = _mapping(body.get("content") or {}, "request body content")
            json_media = _json_content(content)
            if json_media is None:
                raise UnsupportedShape(f"request body types {list(content)}")
        media_type, media = json_media
        body_type = self.body_type(
            media.get("schema"), body_location / "content" / media_type / "schema"
        )
        if body.get("required") is not True:
            if "None" in _split_union(body_type.annotation):
                raise UnsupportedShape(
                    "optional request body that may also be null", body_location
                )
            return PyType(_union([body_type.annotation, "None"]), body_type.model), True
        return body_type, False

    def _url(self, path: str, params: list[Param]) -> str:
        """The path as a Python string literal, with path parameters filled in."""
        path_params = {p.wire_name: p for p in params if p.location == "path"}
        literal_text = _PLACEHOLDER.sub("", path)
        if "{" in literal_text or "}" in literal_text:
            raise UnsupportedShape("path has unbalanced braces")
        used: set[str] = set()
        pieces: list[str] = []
        end = 0
        for match in _PLACEHOLDER.finditer(path):
            name = match.group(1)
            if name not in path_params:
                raise UnsupportedShape(
                    f"path placeholder {{{name}}} is not a parameter"
                )
            used.add(name)
            pieces.append(_escape(path[end : match.start()]))
            pieces.append("{" + self.path_value(path_params[name]) + "}")
            end = match.end()
        pieces.append(_escape(path[end:]))
        unused = sorted(set(path_params) - used)
        if unused:
            raise UnsupportedShape(f"path parameters {unused} are not in the path")
        url = "".join(pieces)
        return f'f"{url}"' if used else f'"{url}"'

    def _query_lines(self, p: Param, indent: str) -> list[str]:
        key = f'"{_escape(p.wire_name)}"'
        self._current.locals.add("params")
        if p.shape == "object":
            self._current.locals.update({"fields", "key", "value"})
            if p.style == "deepObject":
                prefix = _escape(p.wire_name).replace("{", "{{").replace("}", "}}")
                key = f'f"{prefix}[{{key}}]"'
            else:
                key = "key"
            return [
                *_call(
                    indent,
                    f"fields = {p.name}.model_dump",
                    ['mode="json"', "by_alias=True", "exclude_none=True"],
                ),
                f"{indent}for key, value in fields.items():",
                *_append(f"{indent}    ", key, "value"),
            ]
        item = p.item
        assert item is not None
        if p.shape == "scalar":
            self._uses(item.value)
            return _append(indent, key, item.value.format(p.name))
        if p.explode:
            self._current.locals.add("item")
            self._uses(item.value)
            return [
                f"{indent}for item in {p.name}:",
                *_append(f"{indent}    ", key, item.value.format("item")),
            ]
        joined = self._joined(_ARRAY_SEPARATORS[p.style], item, p.name)
        return _append(indent, key, joined)

    def _joined(self, separator: str, item: Scalar, name: str) -> _Expr:
        """The items of the list `name` as text, joined into one string."""
        self._uses(item.text)
        head = f'"{separator}".join'
        if item.text == "{}":
            return _Call(head, (name,))
        element = item.text.format("item")
        return _Call(head, (_Generator(element, f"for item in {name}"),))

    def _header_lines(self, p: Param, indent: str) -> list[str]:
        self._current.locals.add("headers")
        item = p.item
        assert item is not None
        value: _Expr
        if p.shape == "array":
            value = self._joined(",", item, p.name)
        else:
            self._uses(item.text)
            value = item.text.format(p.name)
        return _lines(value, indent, f'headers["{_escape(p.wire_name)}"] = ')

    def _check_names(self, function_name: str, params: list[Param]) -> None:
        if function_name in self.function_names:
            raise UnsupportedShape(f"duplicate function name {function_name}")
        if function_name in _MODULE_NAMES or function_name in self.api_modules:
            raise UnsupportedShape(
                f"function {function_name} would shadow {function_name} in the client"
            )
        shadowed = sorted(self._current.modules & self.function_names)
        if shadowed:
            raise UnsupportedShape(
                f"models module {shadowed[0]} is shadowed by function {shadowed[0]}"
            )
        taken = self._current.locals | self._current.modules
        seen: set[str] = set()
        for p in params:
            if p.name in seen:
                raise UnsupportedShape(f"two parameters are named {p.name}")
            seen.add(p.name)
            if p.name in taken:
                raise UnsupportedShape(
                    f"parameter {p.wire_name} would shadow {p.name} in the client"
                )

    def _adapter(self, name: str, annotation: str) -> str:
        if name in self.adapters:
            raise UnsupportedShape(f"type adapter {name} is already taken")
        self.adapters[name] = annotation
        return name

    def add(
        self,
        method: str,
        path: str,
        operation: Any,
        path_parameters: Any = None,
        *,
        location: Loc | None = None,
    ) -> None:
        """Add the function for one operation, found at `location`, or raise
        UnsupportedShape and leave the module as it was."""
        if location is None:
            location = Loc(self.spec_name) / "paths" / path / method.lower()
        # Work on a copy so a failure part way leaves no trace in the module.
        snapshot = (
            set(self.api_modules),
            set(self.primitive_imports),
            dict(self.adapters),
            self.quotes_path,
        )
        self._current = _Function()
        try:
            with _at(location):
                operation = _mapping(operation, "operation")
                self._add(method, path, operation, path_parameters, location)
        except UnsupportedShape:
            (
                self.api_modules,
                self.primitive_imports,
                self.adapters,
                self.quotes_path,
            ) = snapshot
            raise

    def _add(
        self,
        method: str,
        path: str,
        operation: dict[str, Any],
        path_parameters: Any,
        location: Loc,
    ) -> None:
        if "operationId" not in operation:
            raise UnsupportedShape("operation has no operationId")
        operation_id = _identifier(str(operation["operationId"]))
        params = [
            self.param(p, param_location)
            for p, param_location in self.resolved_params(
                path_parameters, operation.get("parameters"), location
            )
        ]
        params.sort(key=lambda p: not p.required)

        url_literal = self._url(path, params)
        query = [p for p in params if p.location == "query"]
        headers = [p for p in params if p.location == "header"]
        docstring = f"{method} {_escape(path)}"

        returns = self.response(operation, location)
        if returns is None:
            if method != "GET":
                raise UnsupportedShape(f"non-JSON response to {method}")
            if query or headers or "requestBody" in operation:
                raise UnsupportedShape("non-JSON response with a query, header or body")
            function_name = f"{operation_id}_path"
            path_params = [_parameter(p.name, p.annotation) for p in params]
            lines = _call(
                "",
                f"def {function_name}",
                ["*", *path_params] if path_params else [],
                " -> str:",
            )
            lines.append(f'    """{docstring}, which does not return JSON."""')
            lines.append(f"    return {url_literal}")
            self._check_names(function_name, params)
            self.functions.append("\n".join(lines))
            self.function_names.add(function_name)
            return
        request_body = self.request_body(operation, location)
        body, optional_body = request_body or (None, False)
        self._current.locals.add("transport")

        keyword_only = [
            _parameter(p.name, p.annotation)
            if p.required
            else _parameter(p.name, _union([p.annotation, "None"]), " = None")
            for p in params
        ]
        if body is not None:
            self._current.locals.add("body")
            keyword_only.append(
                _parameter("body", body.annotation, " = None" if optional_body else "")
            )
        signature: list[_Expr] = [
            "transport: Transport",
            *(["*", *keyword_only] if keyword_only else []),
        ]

        lines = _call(
            "", f"async def {operation_id}", signature, f" -> {returns.annotation}:"
        )
        lines.append(f'    """{docstring}"""')
        if query:
            self.uses_query_value = True
            self._current.locals.add("tuple")
            lines.append("    params: list[tuple[str, QueryValue]] = []")
            for p in query:
                if p.required:
                    lines += self._query_lines(p, "    ")
                else:
                    lines.append(f"    if {p.name} is not None:")
                    lines += self._query_lines(p, "        ")
        if headers:
            lines.append("    headers: dict[str, str] = {}")
            for p in headers:
                if p.required:
                    lines += self._header_lines(p, "    ")
                else:
                    lines.append(f"    if {p.name} is not None:")
                    lines += self._header_lines(p, "        ")
        json_arg = self._body_lines(body, optional_body, operation_id, lines)
        call_args = [
            f'"{method}"',
            url_literal,
            f"params={'tuple(params)' if query else 'None'}",
            f"headers={'headers' if headers else 'None'}",
            f"json={json_arg}",
        ]
        if returns == _NONE:
            lines += _call("    ", "await transport", call_args)
        else:
            self._current.locals.add("response")
            lines += _call("    ", "response = await transport", call_args)
            if returns.model:
                validate = f"{returns.annotation}.model_validate"
            else:
                adapter = self._adapter(
                    f"_{operation_id.upper()}_RESPONSE", returns.annotation
                )
                validate = f"{adapter}.validate_python"
            lines += _call("    ", f"return {validate}", ["response"])
        self._check_names(operation_id, params)
        self.uses_transport = True
        self.functions.append("\n".join(lines))
        self.function_names.add(operation_id)

    def _body_lines(
        self,
        body: PyType | None,
        optional: bool,
        operation_id: str,
        lines: list[str],
    ) -> str:
        """Append the statements that turn `body` into JSON; the expression to send."""
        if body is None:
            return "None"
        if body.model and not optional:
            return 'body.model_dump(mode="json")'
        if body.model:
            dump = "body.model_dump"
        else:
            adapter = self._adapter(f"_{operation_id.upper()}_BODY", body.annotation)
            dump = f"{adapter}.dump_python"
        self._current.locals.add("payload")
        args = ['mode="json"'] if body.model else ["body", 'mode="json"']
        if not optional:
            lines += _call("    ", f"payload = {dump}", args)
            return "payload"
        lines.append("    payload: object = None")
        lines.append("    if body is not None:")
        lines += _call("        ", f"payload = {dump}", args)
        return "payload"

    def _imports(self) -> str:
        """The import block, grouped and sorted the way isort and ruff do."""
        names: dict[str, set[str]] = {}
        for module, name in self.primitive_imports:
            names.setdefault(module, set()).add(name)
        if self.quotes_path:
            names.setdefault("urllib.parse", set()).add("quote")
        if self.adapters:
            names.setdefault("pydantic", set()).add("TypeAdapter")
        if self.api_modules:
            names[self.models_package] = set(self.api_modules)
        client_names = set()
        if self.uses_query_value:
            client_names.add("QueryValue")
        if self.uses_transport:
            client_names.add("Transport")
        if client_names:
            names.setdefault(self.client_package, set()).update(client_names)

        first_party = {self.models_package, self.client_package}
        sections: list[list[str]] = [[], [], []]
        for module in sorted(names, key=lambda m: (m.lower(), m)):
            if module in first_party:
                section = sections[2]
            elif module in _THIRD_PARTY:
                section = sections[1]
            else:
                section = sections[0]
            imported = ", ".join(sorted(names[module], key=_import_order))
            section.append(f"from {module} import {imported}")
        return "\n\n".join("\n".join(s) for s in sections if s)

    def render(self) -> str:
        top = (HEADER.format(spec=self.spec_name) + self._imports()).rstrip("\n")
        adapters: list[str] = []
        for name, annotation in self.adapters.items():
            if len(f"{name} = TypeAdapter(") <= LINE_LENGTH:
                adapters += _call("", f"{name} = TypeAdapter", [annotation])
            else:  # the formatters wrap a long name's value in parentheses
                adapters += [
                    f"{name} = (",
                    *_call("    ", "TypeAdapter", [annotation]),
                    ")",
                ]
        if adapters:
            # isort puts one blank line between imports and anything but a def.
            top += "\n\n" + "\n".join(adapters)
        return "\n\n\n".join([top, *self.functions]) + "\n"


def _append(indent: str, key: str, value: _Expr) -> list[str]:
    """`params.append((key, value))`."""
    return _call(indent, "params.append", [_Tuple((key, value))])


def _import_order(name: str) -> tuple[int, str, str]:
    """isort's default order for names in one import: constants, classes, then
    everything else, each case-insensitively."""
    if name.isupper() and len(name) > 1:
        kind = 0
    elif name[:1].isupper():
        kind = 1
    else:
        kind = 2
    return kind, name.lower(), name


def _problem(error: UnsupportedShape, entry: Loc) -> str:
    """`error` at the part of the spec at fault, and the operation that led there
    when that is somewhere else."""
    location = error.location or entry
    text = f"{location}: {error}"
    if not entry.contains(location):
        text += f" (from {entry})"
    return text


def _is_generated(path: Path) -> bool:
    try:
        with path.open(encoding="utf-8") as f:
            return f.readline().startswith(GENERATED_MARKER)
    except (OSError, UnicodeDecodeError):
        return False


def _not_generated(path: Path) -> str:
    return f"{path}: exists and was not generated, not overwriting"


@dataclass
class _Output:
    files: dict[str, str]
    problems: list[str]
    selected: set[str] | None
    """The module files this run is responsible for, when given a subset of the
    specs; None means every generated module in the output directory."""
    kept: set[str]
    """Modules of specs that failed outright, left as they are."""

    def is_stale(self, path: Path) -> bool:
        """A generated module this run would remove."""
        return (
            path.name not in self.files
            and path.name not in self.kept
            and (self.selected is None or path.name in self.selected)
            and _is_generated(path)
        )


def _render(
    spec_dir: Path,
    *,
    models_package: str,
    client_package: str | None,
    specs: Sequence[str | Path] | None,
    exclude: Sequence[str] | None,
    versions: Collection[str] | None,
) -> _Output:
    if client_package is None:
        client_package = f"{models_package}.client"
    importlib.invalidate_caches()
    resolver = Resolver(spec_dir, models_package)
    output = _Output(
        files={"__init__.py": TRANSPORT_MODULE},
        problems=[],
        selected=None if specs is None else set(),
        kept=set(),
    )
    problems = output.problems
    names = (
        [p.name for p in discover_specs(spec_dir)]
        if specs is None
        else [str(s) for s in specs]
    )
    names = [
        name
        for name in names
        if not any(fnmatch.fnmatchcase(name, pattern) for pattern in exclude or ())
    ]
    for name in names:
        if PurePath(name).name != name:
            problems.append(f"{name}: not a file name directly inside {spec_dir}")
            continue
        try:
            module_name = resolver.models_module(name)
        except UnsupportedShape as e:
            problems.append(f"{name}: {e}")
            continue
        if module_name == "__init__":
            problems.append(f"{name}: would overwrite the Transport module")
            continue
        module_file = f"{module_name}.py"
        if output.selected is not None:
            output.selected.add(module_file)
        problem_count = len(problems)
        try:
            spec = resolver.spec(name)
        except UnsupportedShape as e:
            problems.append(f"{name}: {e}")
            output.kept.add(module_file)
            continue
        writer = ModuleWriter(
            name,
            resolver,
            models_package=models_package,
            client_package=client_package,
        )
        _add_operations(writer, resolver, spec, Loc(name), versions, problems)
        if writer.functions:
            output.files[module_file] = writer.render()
        elif len(problems) > problem_count:
            # Nothing could be generated: keep the last good module rather than
            # remove it over what may be a passing mistake in the spec.
            output.kept.add(module_file)
    return output


def _add_operations(
    writer: ModuleWriter,
    resolver: Resolver,
    spec: dict[str, Any],
    root: Loc,
    versions: Collection[str] | None,
    problems: list[str],
) -> None:
    paths = spec.get("paths")
    if paths is None:
        return
    if not isinstance(paths, dict):
        problems.append(f"{root / 'paths'}: paths is a {type(paths).__name__}")
        return
    for path, raw_item in paths.items():
        path = str(path)
        if raw_item is None:
            continue
        try:
            item, item_location = resolver.follow(
                raw_item, root / "paths" / path, "path item"
            )
        except UnsupportedShape as e:
            problems.append(_problem(e, root / "paths" / path))
            continue
        for method in HTTP_METHODS:
            if method not in item:
                continue
            entry = root / "paths" / path / method
            segments = path.split("/")
            if versions is not None and (
                len(segments) < 3 or segments[0] or segments[1] not in versions
            ):
                problems.append(
                    f"{entry}: path must start with one of the versions "
                    f"{sorted(versions)}"
                )
                continue
            try:
                writer.add(
                    method.upper(),
                    path,
                    item[method],
                    item.get("parameters"),
                    location=item_location / method,
                )
            except UnsupportedShape as e:
                problems.append(_problem(e, entry))


def render(
    spec_dir: Path,
    *,
    models_package: str,
    client_package: str | None = None,
    specs: Sequence[str | Path] | None = None,
    exclude: Sequence[str] | None = None,
    versions: Collection[str] | None = None,
) -> tuple[dict[str, str], list[str]]:
    """The client package's files by name, and the problems found. Writes nothing.

    `specs` names spec files directly inside `spec_dir` (default: all of them), and
    `exclude` holds glob patterns of file names to leave out. When `versions` is
    given, every path must start with `/<version>/` for one of them.
    """
    output = _render(
        spec_dir,
        models_package=models_package,
        client_package=client_package,
        specs=specs,
        exclude=exclude,
        versions=versions,
    )
    return output.files, output.problems


def generate(
    spec_dir: Path,
    output_dir: Path,
    *,
    models_package: str,
    client_package: str | None = None,
    specs: Sequence[str | Path] | None = None,
    exclude: Sequence[str] | None = None,
    versions: Collection[str] | None = None,
) -> list[str]:
    """Write the client package into `output_dir` and return the problems found.

    Generated modules for specs that no longer have operations, or are excluded,
    are removed. With `specs`, only the modules of those specs are touched. A spec
    that could not be read, or yielded nothing but problems, keeps its last
    generated module. A file the generator did not write is never overwritten or
    removed.
    """
    output = _render(
        spec_dir,
        models_package=models_package,
        client_package=client_package,
        specs=specs,
        exclude=exclude,
        versions=versions,
    )
    problems = output.problems
    output_dir.mkdir(parents=True, exist_ok=True)
    for name in sorted(output.files):
        target = output_dir / name
        if target.exists() and not _is_generated(target):
            problems.append(_not_generated(target))
            del output.files[name]
            output.kept.add(name)
    for stale in output_dir.glob("*.py"):
        if output.is_stale(stale):
            stale.unlink()
    for name, text in output.files.items():
        (output_dir / name).write_text(text, encoding="utf-8")
    return problems


def check(
    spec_dir: Path,
    output_dir: Path,
    *,
    models_package: str,
    client_package: str | None = None,
    specs: Sequence[str | Path] | None = None,
    exclude: Sequence[str] | None = None,
    versions: Collection[str] | None = None,
) -> list[str]:
    """The problems found, plus every way `output_dir` differs from what
    `generate` would write. Writes nothing."""
    output = _render(
        spec_dir,
        models_package=models_package,
        client_package=client_package,
        specs=specs,
        exclude=exclude,
        versions=versions,
    )
    problems = output.problems
    for name, text in sorted(output.files.items()):
        target = output_dir / name
        if not target.exists():
            problems.append(f"{target}: missing")
        elif not _is_generated(target):
            problems.append(_not_generated(target))
            output.kept.add(name)
        elif target.read_text(encoding="utf-8") != text:
            problems.append(f"{target}: out of date")
    if output_dir.is_dir():
        for stale in sorted(output_dir.glob("*.py")):
            if output.is_stale(stale):
                problems.append(f"{stale}: stale, would be removed")
    return problems
