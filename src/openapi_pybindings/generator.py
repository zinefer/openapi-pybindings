"""Generate typed async client functions from OpenAPI specs.

Writes one module per spec into the output directory, with one function per
operation. Request and response bodies use the pydantic models datamodel-codegen
already generated into the models package (one module per spec file), so this must
run after it. Every function takes a `Transport`, which owns the host, auth and
shared headers, and returns the parsed response.

Paths are used as written in the spec (`/v1/movies/...`). A GET route that does
not return JSON gets a `<operation>_path` function instead.

A shape this generator does not understand is an error, never `Any`: the point of
the client is that a type checker sees every route, parameter and body the caller
relies on. Each problem names the JSON pointer of the part of the spec at fault.

The output is laid out the way ruff and black format it (sorted imports, lines
split with a trailing comma when they would pass 88 columns), so it can live in a
project that checks formatting.
"""

