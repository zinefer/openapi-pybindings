@dataclass(frozen=True)
class Loc:
    """A place in a spec: a file and a JSON pointer into it."""

    file: str
    pointer: str = ""

    def __truediv__(self, key: object) -> Loc:
        token = str(key).replace("~", "~0").replace("/", "~1")
        return Loc(self.file, f"{self.pointer}/{token}")

    def parent(self) -> Loc:
        return Loc(self.file, self.pointer.rpartition("/")[0])

    def contains(self, other: Loc) -> bool:
        return self.file == other.file and (
            other.pointer == self.pointer
            or other.pointer.startswith(self.pointer + "/")
        )

    def __str__(self) -> str:
        return f"{self.file}#{self.pointer}" if self.pointer else self.file


class UnsupportedShape(Exception):
    """The spec uses something the generator cannot type precisely."""

    def __init__(self, message: str, location: Loc | None = None) -> None:
        super().__init__(message)
        self.location = location


@contextmanager
def _at(location: Loc) -> Iterator[None]:
    """Attribute an UnsupportedShape raised inside to `location`, unless a more
    precise location was already given."""
    try:
        yield
    except UnsupportedShape as e:
        if e.location is None:
            e.location = location
        raise


def _identifier(name: str) -> str:
    """`name` as a snake_case Python identifier."""
    snake = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).replace("-", "_").lower()
    snake = re.sub(r"\W", "_", snake)
    if snake[:1].isdigit():
        snake = f"_{snake}"
    if not snake.isidentifier():
        raise UnsupportedShape(f"{name!r} cannot be made a Python identifier")
    return f"{snake}_" if keyword.iskeyword(snake) else snake


def _escape(text: str) -> str:
    """`text` escaped for the inside of a double-quoted Python string."""
    return json.dumps(text, ensure_ascii=False)[1:-1]


def _mapping(value: Any, what: str) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise UnsupportedShape(f"{what} is a {type(value).__name__}, not a mapping")
    return value


def _list(value: Any, what: str) -> list[Any]:
    if value is None:
        return []
    if not isinstance(value, list):
        raise UnsupportedShape(f"{what} is a {type(value).__name__}, not a list")
    return value


def _without_null(schema: dict[str, Any]) -> tuple[dict[str, Any], bool]:
    """`schema` without its null alternative, and whether it had one: OpenAPI 3.0
    `nullable: true`, or 3.1 `type: [T, "null"]`."""
    type_ = schema.get("type")
    if isinstance(type_, list) and "null" in type_:
        rest = [t for t in type_ if t != "null"]
        if len(rest) == 1:
            return {**schema, "type": rest[0]}, True
    return schema, schema.get("nullable") is True


def _split_union(annotation: str) -> list[str]:
    """The members of a `A | B` annotation, ignoring `|` inside brackets."""
    parts: list[str] = []
    depth = start = 0
    for i, char in enumerate(annotation):
        if char == "[":
            depth += 1
        elif char == "]":
            depth -= 1
        elif depth == 0 and annotation.startswith(" | ", i):
            parts.append(annotation[start:i])
            start = i + 3
    parts.append(annotation[start:])
    return parts


def _union(annotations: Sequence[str]) -> str:
    """`A | B`, flattened and without repeats, with None last."""
    parts: list[str] = []
    for annotation in annotations:
        for part in _split_union(annotation):
            if part not in parts:
                parts.append(part)
    if "None" in parts:
        parts.remove("None")
        parts.append("None")
    return " | ".join(parts)


# Just enough of an expression tree to lay generated code out the way ruff and
# black format it: on one line if it fits, otherwise split the outermost brackets,
# with a trailing comma the formatters then keep.


@dataclass(frozen=True)
class _Call:
    head: str
    args: tuple[_Expr, ...]


@dataclass(frozen=True)
class _Tuple:
    items: tuple[_Expr, ...]


@dataclass(frozen=True)
class _Generator:
    """`element clause`, as the only argument of a call."""

    element: _Expr
    clause: str


@dataclass(frozen=True)
class _Annotated:
    """`before A | B after`, such as a parameter and its default; split, each
    member of the union starts a line."""

    before: str
    members: tuple[str, ...]
    after: str


_Expr = str | _Call | _Tuple | _Generator | _Annotated


def _flat(expr: _Expr) -> str:
    if isinstance(expr, str):
        return expr
    if isinstance(expr, _Call):
        return f"{expr.head}({', '.join(_flat(a) for a in expr.args)})"
    if isinstance(expr, _Tuple):
        return f"({', '.join(_flat(i) for i in expr.items)})"
    if isinstance(expr, _Generator):
        return f"{_flat(expr.element)} {expr.clause}"
    return f"{expr.before}{' | '.join(expr.members)}{expr.after}"


def _lines(expr: _Expr, indent: str, prefix: str = "", suffix: str = "") -> list[str]:
    """`prefix expr suffix` at `indent`, split over lines as the formatters would."""
    flat = f"{indent}{prefix}{_flat(expr)}{suffix}"
    if len(flat) <= LINE_LENGTH or isinstance(expr, str):
        return [flat]
    inner = indent + "    "
    if isinstance(expr, _Generator):
        return [*_lines(expr.element, indent, prefix), f"{indent}{expr.clause}{suffix}"]
    if isinstance(expr, _Annotated):
        *first, last = expr.members
        return [
            f"{indent}{prefix}{expr.before}{first[0]}",
            *(f"{indent}| {member}" for member in first[1:]),
            f"{indent}| {last}{expr.after}{suffix}",
        ]
    if isinstance(expr, _Call):
        if not expr.args:
            return [flat]
        if len(expr.args) == 1 and isinstance(expr.args[0], _Generator):
            body = _lines(expr.args[0], inner)  # no trailing comma after one
        else:
            body = [line for arg in expr.args for line in _lines(arg, inner, "", ",")]
        return [f"{indent}{prefix}{expr.head}(", *body, f"{indent}){suffix}"]
    body = [line for item in expr.items for line in _lines(item, inner, "", ",")]
    return [f"{indent}{prefix}(", *body, f"{indent}){suffix}"]


def _call(indent: str, head: str, args: Sequence[_Expr], tail: str = "") -> list[str]:
    """`head(args)tail` on one line if it fits, otherwise one argument per line
    with a trailing comma, which black and ruff format leave as it is."""
    return _lines(_Call(head, tuple(args)), indent, suffix=tail)


def _parameter(name: str, annotation: str, default: str = "") -> _Expr:
    """`name: annotation = default` in a signature."""
    members = _split_union(annotation)
    if len(members) == 1:
        return f"{name}: {annotation}{default}"
    return _Annotated(f"{name}: ", tuple(members), default)


def _is_json(media_type: str) -> bool:
    essence = media_type.split(";", 1)[0].strip().lower()
    return essence == "application/json" or (
        essence.startswith("application/") and essence.endswith("+json")
    )


def _json_content(content: dict[str, Any]) -> tuple[str, dict[str, Any]] | None:
    """The JSON media type of a `content` map and its media type object,
    preferring `application/json`."""
    if "application/json" in content:
        media = content["application/json"] or {}
        return "application/json", _mapping(media, "application/json")
    for media_type, media in content.items():
        if _is_json(str(media_type)):
            return str(media_type), _mapping(media or {}, str(media_type))
    return None


